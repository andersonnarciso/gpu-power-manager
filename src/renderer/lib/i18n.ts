const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  'pt-BR': ptBR,
  en,
};

export type TranslationVars = Record<string, string | number>;

export type TranslateFn = (key: TranslationKey, vars?: TranslationVars) => string;

function interpolate(template: string, vars?: TranslationVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

/** Translate a key for an explicit locale. */
export function translate(locale: Locale, key: TranslationKey, vars?: TranslationVars): string {
  const dictionary = dictionaries[locale] ?? dictionaries[DEFAULT_LOCALE];
  const fallback = dictionaries[DEFAULT_LOCALE];
  const template = dictionary[key] ?? fallback[key] ?? key;
  return interpolate(template, vars);
}

/* ------------------------------------------------- current locale (observable) */

let currentLocale: Locale = DEFAULT_LOCALE;
const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return currentLocale;
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

/** Switch the active locale for the whole renderer. */
export function setLocale(locale: Locale): void {
  if (currentLocale === locale) return;
  currentLocale = locale;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
  }
  listeners.forEach((listener) => listener());
}

/**
 * Module level translator bound to the active locale. Use it outside React
 * (stores, helpers); inside components prefer {@link useT}.
 */
export function t(key: TranslationKey, vars?: TranslationVars): string {
  return translate(currentLocale, key, vars);
}

/**
 * React hook returning a translator bound to the active locale. Components
 * re-render automatically when the locale changes.
 */
export function useT(): TranslateFn {
  const locale = useSyncExternalStore(subscribeLocale, getLocale, getLocale);
  return useCallback(
    (key: TranslationKey, vars?: TranslationVars) => translate(locale, key, vars),
    [locale],
  );
}

/** Label for a sample count with the correct singular form. */
export function useSamplesLabel(count: number): string {
  const t = useT();
  return count === 1 ? t('common.sampleOne', { count }) : t('common.samples', { count });
}
